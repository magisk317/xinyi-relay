type DesktopI18nValue = {
  locale: SupportedLocale
  t: (key: MessageKey) => string
  appName: string
  brandName: string
}

const DesktopI18nContext = createContext<DesktopI18nValue | null>(null)

export function DesktopI18nProvider({ children }: PropsWithChildren) {
  const { bootstrap } = useDesktop()

  const locale = useMemo(
    () => resolveLocale(bootstrap?.languageTag || navigator.language || 'en'),
    [bootstrap?.languageTag]
  )

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<DesktopI18nValue>(() => {
    const appName = localeMessages[locale]['app.name']
    const brandName = localeMessages[locale]['app.brand']
    return {
      locale,
      t: (key) => localeMessages[locale][key] ?? enMessages[key] ?? key,
      appName,
      brandName
    }
  }, [locale])

  return <DesktopI18nContext.Provider value={value}>{children}</DesktopI18nContext.Provider>
}

export function useDesktopI18n() {
  const value = useContext(DesktopI18nContext)
  if (!value) {
    throw new Error('useDesktopI18n must be used inside DesktopI18nProvider')
  }
  return value
}

export function translateSenderType(
  type: number,
  t: (key: string) => string
): string {
  const map: Record<number, string> = {
    0: 'senders.type.dingtalkGroup',
    1: 'senders.type.email',
    2: 'senders.type.bark',
    3: 'senders.type.webhook',
    4: 'senders.type.weworkRobot',
    5: 'senders.type.weworkAgent',
    6: 'senders.type.serverchan',
    7: 'senders.type.telegram',
    8: 'senders.type.sms',
    9: 'senders.type.feishu',
    10: 'senders.type.pushplus',
    11: 'senders.type.gotify',
    12: 'senders.type.dingtalkInner',
    13: 'senders.type.feishuApp',
    14: 'senders.type.urlScheme',
    15: 'senders.type.socket',
    16: 'senders.type.ntfy',
    17: 'senders.type.yunhu'
  }
  const key = map[type]
  return key ? t(key) : `Type ${type}`
}

function resolveLocale(languageTag: string): SupportedLocale {
  const normalized = languageTag.trim().toLowerCase()
  if (normalized.startsWith('zh-tw') || normalized.startsWith('zh-hk') || normalized.startsWith('zh-mo')) {
    return 'zh-TW'
  }
  if (normalized.startsWith('zh')) {
    return 'zh-CN'
  }
  return 'en'
}
