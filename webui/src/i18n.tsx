const messages: Record<SupportedLocale, Messages> = {
  en: enMessages,
  'zh-CN': zhCnMessages,
  'zh-TW': zhTwMessages
}

export type TranslationKey = keyof typeof enMessages

type I18nContextValue = {
  selectedLocale: LocaleSetting
  locale: SupportedLocale
  serverLanguageTag: string
  setSelectedLocale: (next: LocaleSetting) => void
  syncServerLanguageTag: (languageTag: string) => void
  t: (key: TranslationKey, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ''))
}

export function resolveBrowserLocale(): SupportedLocale {
  const raw = (navigator.language || 'en').toLowerCase()
  if (raw.startsWith('zh-tw') || raw.startsWith('zh-hk') || raw.startsWith('zh-hant')) {
    return 'zh-TW'
  }
  if (raw.startsWith('zh')) {
    return 'zh-CN'
  }
  return 'en'
}

export function resolveLanguageTagLocale(languageTag: string): SupportedLocale | null {
  const normalized = languageTag.trim()
  if (normalized === 'zh-CN') return 'zh-CN'
  if (normalized === 'zh-TW') return 'zh-TW'
  if (normalized === 'en') return 'en'
  return null
}

export function resolveLocale(setting: LocaleSetting, serverLanguageTag = ''): SupportedLocale {
  if (setting !== 'system') return setting
  return resolveLanguageTagLocale(serverLanguageTag) ?? resolveBrowserLocale()
}

export function getStoredLocaleSetting(): LocaleSetting {
  const raw = window.localStorage.getItem(STORAGE_KEY)
  if (raw === 'en' || raw === 'zh-CN' || raw === 'zh-TW' || raw === 'system') {
    return raw
  }
  return 'system'
}

export function translateStatic(
  key: TranslationKey,
  params?: Record<string, string | number>,
  setting: LocaleSetting = getStoredLocaleSetting(),
  serverLanguageTag = ''
): string {
  const locale = resolveLocale(setting, serverLanguageTag)
  const message = messages[locale][key] ?? enMessages[key] ?? key
  return interpolate(message, params)
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [selectedLocale, setSelectedLocaleState] = useState<LocaleSetting>(() => getStoredLocaleSetting())
  const [serverLanguageTag, setServerLanguageTag] = useState('')
  const locale = useMemo(() => resolveLocale(selectedLocale, serverLanguageTag), [selectedLocale, serverLanguageTag])

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, selectedLocale)
  }, [selectedLocale])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    selectedLocale,
    locale,
    serverLanguageTag,
    setSelectedLocale: setSelectedLocaleState,
    syncServerLanguageTag: setServerLanguageTag,
    t: (key, params) => translateStatic(key, params, selectedLocale, serverLanguageTag)
  }), [locale, selectedLocale, serverLanguageTag])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) {
    throw new Error('useI18n must be used inside I18nProvider')
  }
  return value
}

