assert_contains ':desktop:compileKotlinJvm' "$tmp_dir/out"
assert_contains ':desktop:core:jvmTest' "$tmp_dir/out"
assert_contains ':desktop:data:jvmTest' "$tmp_dir/out"
assert_contains ':policy:jvmTest' "$tmp_dir/out"
assert_contains ':relay:contract:jvmTest' "$tmp_dir/out"
assert_contains ':relay:net:jvmTest' "$tmp_dir/out"
assert_contains ':relay:sender:api:jvmTest' "$tmp_dir/out"
printf 'impact\nmagisk-ui-kit/src/main.kt\n' > "$tmp_dir/kit"
bash "$selector" /dev/null "$tmp_dir/kit" > "$tmp_dir/out"
assert_contains ':magisk-ui-kit:testAndroidHostTest' "$tmp_dir/out"
assert_contains ':magisk-ui-kit:billing:testDebugUnitTest' "$tmp_dir/out"
printf 'impact\ndesktop/src/jvmMain/kotlin/Main.kt\n' > "$tmp_dir/desktop_src"
bash "$selector" /dev/null "$tmp_dir/desktop_src" > "$tmp_dir/out"
assert_contains ':desktop:compileKotlinJvm' "$tmp_dir/out"
assert_contains ':desktop:jvmTest' "$tmp_dir/out"
assert_contains ':desktop:core:jvmTest' "$tmp_dir/out"
assert_contains ':desktop:data:jvmTest' "$tmp_dir/out"
