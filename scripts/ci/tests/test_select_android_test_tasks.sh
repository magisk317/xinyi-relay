assert_contains ':mobile:feature:record:testGithubDebugUnitTest' "$tmp_dir/out"
assert_contains ':mobile:feature:settings:testGithubDebugUnitTest' "$tmp_dir/out"
assert_contains ':mobile:ui:testGithubDebugUnitTest' "$tmp_dir/out"
